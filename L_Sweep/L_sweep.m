%% Axes

xlabel('Transition length, L (\mum)', ...
    'FontName','Times New Roman', ...
    'FontSize',18);

ylabel('Normalized power (a.u.)', ...
    'FontName','Times New Roman', ...
    'FontSize',18);

set(gca, ...
    'FontName','Times New Roman', ...
    'FontSize',16, ...
    'LineWidth',1.2, ...
    'TickDir','in', ...
    'Box','on');

